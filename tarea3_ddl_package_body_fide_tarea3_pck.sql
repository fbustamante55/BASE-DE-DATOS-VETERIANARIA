FUNCTION FIDE_FN_SERVICIO_MAS_UTILIZADO
RETURN VARCHAR2 IS
CURSOR C_SERVICIO_MAS_UTILIZADO IS
SELECT NOMBRE
FROM (
SELECT S.NOMBRE, COUNT(*) AS CANTIDAD
FROM TAREA1.FIDE_SERVICIOS_CITA_TB SC
INNER JOIN TAREA1.FIDE_SERVICIOS_TB S
ON SC.ID_SERVICIO = S.ID_SERVICIO
GROUP BY S.NOMBRE
ORDER BY COUNT(*) DESC, S.NOMBRE ASC
)
WHERE ROWNUM = 1;
V_NOMBRE_SERVICIO TAREA1.FIDE_SERVICIOS_TB.NOMBRE%TYPE;
BEGIN
OPEN C_SERVICIO_MAS_UTILIZADO;
FETCH C_SERVICIO_MAS_UTILIZADO INTO V_NOMBRE_SERVICIO;
IF C_SERVICIO_MAS_UTILIZADO%NOTFOUND THEN
CLOSE C_SERVICIO_MAS_UTILIZADO;
RETURN 'SIN REGISTROS';
END IF;
CLOSE C_SERVICIO_MAS_UTILIZADO;
RETURN V_NOMBRE_SERVICIO;
EXCEPTION
WHEN OTHERS THEN
IF C_SERVICIO_MAS_UTILIZADO%ISOPEN THEN
CLOSE C_SERVICIO_MAS_UTILIZADO;
END IF;
DBMS_OUTPUT.PUT_LINE('Error en FIDE_FN_SERVICIO_MAS_UTILIZADO: ' || SQLERRM);
RETURN 'ERROR';
END FIDE_FN_SERVICIO_MAS_UTILIZADO;

