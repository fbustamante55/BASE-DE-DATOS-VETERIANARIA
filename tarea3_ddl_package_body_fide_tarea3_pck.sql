FUNCTION FIDE_FN_MASCOTAS_POR_CLIENTE(
P_ID_CLIENTE IN TAREA1.FIDE_CLIENTES_TB.ID_CLIENTE%TYPE
) RETURN NUMBER IS
CURSOR C_MASCOTAS IS
SELECT COUNT(*)
FROM TAREA1.FIDE_MASCOTAS_TB
WHERE ID_CLIENTE = P_ID_CLIENTE;
V_CANTIDAD NUMBER := 0;
BEGIN
OPEN C_MASCOTAS;
FETCH C_MASCOTAS INTO V_CANTIDAD;
CLOSE C_MASCOTAS;
RETURN NVL(V_CANTIDAD,0);
EXCEPTION
WHEN OTHERS THEN
IF C_MASCOTAS%ISOPEN THEN
CLOSE C_MASCOTAS;
END IF;
DBMS_OUTPUT.PUT_LINE('Error en FIDE_FN_MASCOTAS_POR_CLIENTE: ' || SQLERRM);
RETURN 0;
END FIDE_FN_MASCOTAS_POR_CLIENTE;

FUNCTION FIDE_FN_ULTIMA_CITA_MASCOTA(
P_ID_MASCOTA IN TAREA1.FIDE_MASCOTAS_TB.ID_MASCOTA%TYPE
) RETURN DATE IS
