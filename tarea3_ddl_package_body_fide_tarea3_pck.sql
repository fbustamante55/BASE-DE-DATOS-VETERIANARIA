END IF;
DBMS_OUTPUT.PUT_LINE('Error en FIDE_FN_ULTIMA_CITA_MASCOTA: ' || SQLERRM);
RETURN NULL;
END FIDE_FN_ULTIMA_CITA_MASCOTA;

FUNCTION FIDE_FN_ESTADO_FACTURA(
P_ID_FACTURA IN TAREA1.FIDE_FACTURAS_TB.ID_FACTURA%TYPE
) RETURN VARCHAR2 IS
CURSOR C_ESTADO_FACTURA IS
SELECT E.NOMBRE_ESTADO
FROM TAREA1.FIDE_FACTURAS_TB F
INNER JOIN TAREA1.FIDE_ESTADOS_TB E
ON F.ID_ESTADO = E.ID_ESTADO
WHERE F.ID_FACTURA = P_ID_FACTURA;
V_ESTADO TAREA1.FIDE_ESTADOS_TB.NOMBRE_ESTADO%TYPE;
BEGIN
OPEN C_ESTADO_FACTURA;
FETCH C_ESTADO_FACTURA INTO V_ESTADO;
IF C_ESTADO_FACTURA%NOTFOUND THEN
CLOSE C_ESTADO_FACTURA;
RETURN 'FACTURA NO ENCONTRADA';
END IF;
CLOSE C_ESTADO_FACTURA;
RETURN V_ESTADO;
EXCEPTION
WHEN OTHERS THEN
IF C_ESTADO_FACTURA%ISOPEN THEN
CLOSE C_ESTADO_FACTURA;
END IF;
DBMS_OUTPUT.PUT_LINE('Error en FIDE_FN_ESTADO_FACTURA: ' || SQLERRM);
RETURN 'ERROR';
END FIDE_FN_ESTADO_FACTURA;

