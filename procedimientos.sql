CREATE OR REPLACE PROCEDURE FIDE_SERVICIOS_MAS_USADOS_X_ESPECIE_SP IS
BEGIN
DBMS_OUTPUT.PUT_LINE('ESPECIE | SERVICIO | USOS');
FOR r IN (
SELECT
ra.TIPO_ESPECIE AS ESPECIE,
s.NOMBRE AS SERVICIO,
COUNT(*) AS USOS
FROM TAREA1.FIDE_SERVICIOS_CITA_TB sc
JOIN TAREA1.FIDE_SERVICIOS_TB s
ON s.ID_SERVICIO=sc.ID_SERVICIO
JOIN TAREA1.FIDE_CITAS_TB c
ON c.ID_CITA=sc.ID_CITA
JOIN TAREA1.FIDE_MASCOTAS_TB m
ON m.ID_MASCOTA=c.ID_MASCOTA
JOIN TAREA1.FIDE_RAZA_TB ra
ON ra.ID_RAZA=m.ID_RAZA
GROUP BY ra.TIPO_ESPECIE,s.NOMBRE
ORDER BY ra.TIPO_ESPECIE,COUNT(*) DESC,s.NOMBRE
) LOOP
DBMS_OUTPUT.PUT_LINE(r.ESPECIE||' | '||r.SERVICIO||' | '||r.USOS);
END LOOP;
END;

CREATE OR REPLACE PROCEDURE FIDE_CLIENTES_CON_MAS_DE_UNA_MASCOTA_SP IS
BEGIN
DBMS_OUTPUT.PUT_LINE('ID_CLIENTE | NOMBRE_COMPLETO | CANT_MASCOTAS');
FOR r IN (
SELECT
c.ID_CLIENTE,
(c.NOMBRE||' '||c.APELLIDO_PATERNO||' '||c.APELLIDO_MATERNO) AS NOMBRE_COMPLETO,
COUNT(m.ID_MASCOTA) AS CANT_MASCOTAS
FROM TAREA1.FIDE_CLIENTES_TB c
JOIN TAREA1.FIDE_MASCOTAS_TB m
ON m.ID_CLIENTE=c.ID_CLIENTE
GROUP BY c.ID_CLIENTE,c.NOMBRE,c.APELLIDO_PATERNO,c.APELLIDO_MATERNO
HAVING COUNT(m.ID_MASCOTA)>1
ORDER BY COUNT(m.ID_MASCOTA) DESC,c.ID_CLIENTE
) LOOP
DBMS_OUTPUT.PUT_LINE(r.ID_CLIENTE||' | '||r.NOMBRE_COMPLETO||' | '||r.CANT_MASCOTAS);
END LOOP;
END;

CREATE OR REPLACE PROCEDURE FIDE_MASCOTAS_X_CLIENTE_SP(
P_ID_CLIENTE IN TAREA1.FIDE_CLIENTES_TB.ID_CLIENTE%TYPE
) IS
BEGIN
DBMS_OUTPUT.PUT_LINE('MASCOTAS DEL CLIENTE: '||P_ID_CLIENTE);
DBMS_OUTPUT.PUT_LINE('ID_MASCOTA | NOMBRE | ESPECIE | RAZA | EDAD | PESO');
FOR r IN (
SELECT
m.ID_MASCOTA,
m.NOMBRE AS NOMBRE_MASCOTA,
ra.TIPO_ESPECIE,
ra.NOMBRE_RAZA,
m.EDAD,
m.PESO
FROM TAREA1.FIDE_MASCOTAS_TB m
JOIN TAREA1.FIDE_RAZA_TB ra
ON ra.ID_RAZA=m.ID_RAZA
WHERE m.ID_CLIENTE=P_ID_CLIENTE
ORDER BY m.ID_MASCOTA
) LOOP
DBMS_OUTPUT.PUT_LINE(
r.ID_MASCOTA||' | '||
r.NOMBRE_MASCOTA||' | '||
r.TIPO_ESPECIE||' | '||
r.NOMBRE_RAZA||' | '||
NVL(TO_CHAR(r.EDAD),'NULL')||' | '||
NVL(TO_CHAR(r.PESO),'NULL')
);
END LOOP;
END;

