CREATE OR REPLACE PROCEDURE FIDE_CITAS_CANCELADAS_SP IS
BEGIN
DBMS_OUTPUT.PUT_LINE('CITAS CANCELADAS:');
DBMS_OUTPUT.PUT_LINE('ID_CITA | FECHA_HORA | MASCOTA | CLIENTE');
FOR r IN (
SELECT
c.ID_CITA,
c.FECHA_HORA,
m.NOMBRE AS NOMBRE_MASCOTA,
(cl.NOMBRE||' '||cl.APELLIDO_PATERNO||' '||cl.APELLIDO_MATERNO) AS NOMBRE_CLIENTE
FROM TAREA1.FIDE_CITAS_TB c
JOIN TAREA1.FIDE_MASCOTAS_TB m
ON m.ID_MASCOTA=c.ID_MASCOTA
JOIN TAREA1.FIDE_CLIENTES_TB cl
ON cl.ID_CLIENTE=m.ID_CLIENTE
JOIN TAREA1.FIDE_ESTADOS_TB e
ON e.ID_ESTADO=c.ID_ESTADO
WHERE UPPER(e.NOMBRE_ESTADO)='CANCELADO'
ORDER BY c.FECHA_HORA DESC
) LOOP
DBMS_OUTPUT.PUT_LINE(
r.ID_CITA||' | '||
TO_CHAR(r.FECHA_HORA,'YYYY-MM-DD HH24:MI')||' | '||
r.NOMBRE_MASCOTA||' | '||
r.NOMBRE_CLIENTE
);
END LOOP;
END;

